        while (true) {
            if (currentSpeedKmh > 1.5f) {
                val step = (currentSpeedKmh / 2400f).coerceIn(0.004f, 0.06f)
                roadPhase = (roadPhase + step) % 1f
            }
            delay(16L)
        }
    }

